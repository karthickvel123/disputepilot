"""Interactive CLI script to configure .env safely with Gemini and Razorpay API keys."""

import getpass
import hashlib
import re
import secrets
from pathlib import Path


def make_password_hash(password: str) -> str:
    """Return the same salted scrypt format accepted by the application."""
    if len(password) < 10:
        raise ValueError("Reviewer password must be at least 10 characters.")
    salt = secrets.token_bytes(16)
    key = hashlib.scrypt(password.encode("utf-8"), salt=salt, n=16384, r=8, p=1)
    return f"{salt.hex()}:{key.hex()}"


def main() -> None:
    print("=" * 60)
    print(" DisputePilot Secure API Key Setup")
    print("=" * 60)
    print("This will create a local .env file (git-ignored).")
    print("Your credentials will never be committed to Git.\n")

    # 1. Gemini API Key
    print("[1/4] Google Gemini API Key")
    print("Used for automated AI dispute triage & rebuttal drafting.")
    gemini_key = getpass.getpass("Enter GEMINI_API_KEY (typing hidden, or press Enter to skip): ").strip()

    # 2. Razorpay Key ID
    print("\n[2/4] Razorpay Test Key ID")
    print("From Razorpay Dashboard -> Account & Settings -> API Keys (e.g. rzp_test_...)")
    rzp_key_id = input("Enter RAZORPAY_KEY_ID (or press Enter to skip): ").strip()

    # 3. Razorpay Key Secret
    rzp_key_secret = ""
    if rzp_key_id:
        print("\n[3/4] Razorpay Key Secret")
        rzp_key_secret = getpass.getpass("Enter RAZORPAY_KEY_SECRET (typing hidden): ").strip()
    else:
        print("\n[3/4] Skipping Razorpay Key Secret (No Key ID provided).")

    # 4. Razorpay Webhook Secret
    rzp_webhook_secret = ""
    if rzp_key_id:
        print("\n[4/4] Razorpay Webhook Secret (Optional)")
        rzp_webhook_secret = getpass.getpass("Enter RAZORPAY_WEBHOOK_SECRET (typing hidden, or press Enter to skip): ").strip()
    else:
        print("\n[4/4] Skipping Razorpay Webhook Secret.")

    reviewer_user = input("Reviewer username [reviewer]: ").strip() or "reviewer"
    if not re.fullmatch(r"[A-Za-z0-9_.-]{3,64}", reviewer_user):
        raise SystemExit("Reviewer username must be 3-64 characters: letters, numbers, dot, underscore, or hyphen.")
    reviewer_password = getpass.getpass("Set reviewer password (minimum 10 characters): ")
    try:
        reviewer_password_hash = make_password_hash(reviewer_password)
    except ValueError as exc:
        raise SystemExit(str(exc)) from exc

    session_secret = secrets.token_hex(32)
    # Credentials must never switch the application into live mode automatically.
    data_mode = "sim"

    env_content = f"""# DisputePilot Local Environment Configuration
# Automatically generated by scripts/setup_keys.py

APP_ENV=production
DATA_MODE={data_mode}

# Google Gemini API
GEMINI_API_KEY={gemini_key}
LLM_API_KEY={gemini_key}

# Razorpay API Credentials
RAZORPAY_KEY_ID={rzp_key_id}
RAZORPAY_KEY_SECRET={rzp_key_secret}
RAZORPAY_WEBHOOK_SECRET={rzp_webhook_secret}

# Security & Session
SESSION_SECRET={session_secret}
COOKIE_SECURE=true
COOKIE_SAMESITE=none

# Reviewer Credentials
REVIEWER_USER={reviewer_user}
REVIEWER_PASSWORD_HASH={reviewer_password_hash}
"""

    env_file = Path(".env")
    env_file.write_text(env_content, encoding="utf-8")
    print("\n" + "=" * 60)
    print(f" SUCCESS: .env file saved to {env_file.resolve()}")
    print(f" Mode set to: DATA_MODE={data_mode}")
    if gemini_key:
        print(" Gemini AI: Configured")
    print(f" Reviewer account: {reviewer_user}")
    if rzp_key_id:
        print(f" Razorpay: Configured ({rzp_key_id[:12]}...); DATA_MODE remains sim")
    print("=" * 60)


if __name__ == "__main__":
    main()
