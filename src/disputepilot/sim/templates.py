def format_ts(ts: int) -> str:
    """Format unix timestamp into readable UTC string."""
    return datetime.datetime.fromtimestamp(ts, tz=datetime.UTC).strftime(
        "%Y-%m-%d %H:%M:%S UTC"
    )


